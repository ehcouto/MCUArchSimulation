uint16 ZeroCross__CopyAtodSamples(uint16 atod_id, uint16 *buffer, uint16 max_items)
{
	uint16 num_items = 0;

#if (ZC_HANDLER_TIMING_US > 0) && (ZC_NUM_ATOD_REQUESTS > 0)
	uint8 index = GPIO_ID_INDEX(atod_id);
	if ((index < ZC_NUM_ATOD_REQUESTS) &&
		(ZeroCross_Atod_Pin_Configuration[index].Atod_Id == atod_id))
	{
		uint16 buffer_index;
    	uint16 current_read_sample_index = ZeroCross_Atod_Read_Index[index];
		sint16 available_items = ZeroCross_Atod_Write_Index[index] - current_read_sample_index;
		if (available_items < 0)
		{
			available_items += ZEROCROSS_ATOD_BUFFER_SIZE;
		}

		num_items = max_items;

		if (num_items > available_items)
		{
			num_items = available_items;
		}

		for(buffer_index = 0; buffer_index < num_items; buffer_index++)
		{
			buffer[buffer_index] = ZeroCross_Atod_Buffer[index][current_read_sample_index];
			current_read_sample_index++;
			if (current_read_sample_index >= ZEROCROSS_ATOD_BUFFER_SIZE)
			{
				current_read_sample_index = 0;
			}
		}
		ZeroCross_Atod_Overrun[index] = FALSE;
		ZeroCross_Atod_Read_Index[index] = current_read_sample_index;
	}
#endif

	return(num_items);
}


