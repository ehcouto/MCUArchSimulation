uint16 ZeroCross__RegisterAtodActivity(ATOD_CHANNEL_DEF channel, ATOD_CHANNEL_RESOLUTION_DEF resolution)
{
    uint16 atod_id = ZEROCROSS_ID_INVALID;

#if (ZC_HANDLER_TIMING_US > 0) && (ZC_NUM_ATOD_REQUESTS > 0)
    BOOL_TYPE already_registered = FALSE;

    //Handle the Duplicate requests
    for(uint8 index = 0; index < ZC_NUM_ATOD_REQUESTS; index++)
    {
    	ZEROCROSS_ATOD_CONFIG_TYPE *cfg_ptr = &ZeroCross_Atod_Pin_Configuration[index];

    	if (cfg_ptr->Atod_Id == ZEROCROSS_ID_INVALID)
    	{
    		uint8 high_id = SRTimerReference__GetTimer() & 0xFF;
    		atod_id = index | (high_id << 8);
    		break;
    	}
    	else if (channel == cfg_ptr->Channel)
        {
    		already_registered = TRUE;
    		break;
        }
    }

    //
    if ((already_registered == FALSE) &&
    	(atod_id != ZEROCROSS_ID_INVALID))
    {
    	uint8 index = GPIO_ID_INDEX(atod_id);
    	ZEROCROSS_ATOD_CONFIG_TYPE *cfg_ptr = &ZeroCross_Atod_Pin_Configuration[index];

    	cfg_ptr->Atod_Id = atod_id;
    	cfg_ptr->Channel = channel;
    	cfg_ptr->Resolution = resolution;

		ZeroCross_Atod_Read_Index[index] = 0;
		ZeroCross_Atod_Write_Index[index] = 0;
		ZeroCross_Atod_Overrun[index] = FALSE;
    }
#endif

    return(atod_id);
}

